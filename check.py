# PID vs FSF vs LQR
# Plant: benda bermassa 1 kg dengan gesekan. State = [posisi x, kecepatan v]
#   x' = v
#   v' = -b*v + u + d  (u = gaya kendali, d = gangguan)
# Tujuan: posisi x menuju target r = 1
import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import solve_continuous_are

b = 1.0   # gesekan
r = 1.0   # target posisi
dt = 0.01   # langkah waktu
t = np.arange(0, 10, dt)  # simulasi 10 detik

# FSF dan LQR
A = np.array([[0, 1], [0, -b]])
B = np.array([[0], [1]])

# FSF: pilih pole -2 dan -3
# polinomial karakteristik: (s+2)(s+3) = s^2 + 5s + 6
# dari A-BK: s^2 + (b+k2)s + k1  ->  k1 = 6, k2 = 5 - b
K_fsf = np.array([6.0, 5.0 - b])

# LQR: K = R^-1 B^T P
Q = np.diag([10, 1])
R = np.array([[1.0]])
P = solve_continuous_are(A, B, Q, R)
K_lqr = (np.linalg.inv(R) @ B.T @ P).ravel()

def simulasi(metode, gangguan):
    x, v, integral, e_lalu = 0.0, 0.0, 0.0, r
    X, U = [], []
    for waktu in t:
        e = r - x
        if metode == "PID":
            integral += e * dt
            turunan = (e - e_lalu) / dt
            u = 8*e + 4*integral + 4*turunan      # Kp=8, Ki=4, Kd=4
            e_lalu = e
        elif metode == "FSF":
            u = -K_fsf @ np.array([x - r, v])
        else:
            u = -K_lqr @ np.array([x - r, v])
        d = 0.5 if (gangguan and waktu >= 5) else 0.0   # gangguan muncul di t=5
        v += (-b*v + u + d) * dt
        x += v * dt
        X.append(x)
        U.append(u)
    return np.array(X), np.array(U)

for gangguan in [False, True]:
    plt.figure()
    print("\nDengan gangguan" if gangguan else "\nTanpa gangguan")
    print("metode  overshoot(%)  error akhir  energi(u^2)")
    for metode in ["PID", "FSF", "LQR"]:
        x, u = simulasi(metode, gangguan)
        overshoot = max(0, (x.max() - r) / r * 100)
        error_akhir = abs(r - x[-1])
        energi = np.sum(u**2) * dt
        print(f"{metode}     {overshoot:8.1f}     {error_akhir:8.3f}     {energi:8.2f}")
        plt.plot(t, x, label=metode)
    plt.axhline(r, color="k", linestyle="--", label="target")
    plt.xlabel("waktu (s)")
    plt.ylabel("posisi x")
    plt.title("Dengan gangguan di t=5" if gangguan else "Tanpa gangguan")
    plt.legend()
    plt.grid()
    plt.savefig("sederhana_gangguan.png" if gangguan else "sederhana_nominal.png", dpi=130)
    plt.show()
print("\nK FSF =", K_fsf, "| K LQR =", K_lqr.round(3))